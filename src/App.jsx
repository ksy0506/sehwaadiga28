const EVENT_TYPES = ["원서접수", "논술", "면접", "발표", "기타"];
const EVENT_COLORS = {
  "원서접수": "bg-blue-50 text-blue-700 ring-blue-200",
  "논술": "bg-violet-50 text-violet-700 ring-violet-200",
  "면접": "bg-emerald-50 text-emerald-700 ring-emerald-200",
  "발표": "bg-amber-50 text-amber-700 ring-amber-200",
  "기타": "bg-slate-100 text-slate-600 ring-slate-200",
};

function dday(ds) {
  const t = new Date(); t.setHours(0, 0, 0, 0);
  const d = new Date(ds + "T00:00:00");
  return Math.round((d - t) / 86400000);
}

function ScheduleTab({ events, saveEvents }) {
  const [d, setD] = useState("");
  const [title, setTitle] = useState("");
  const [univ, setUniv] = useState("");
  const [type, setType] = useState("원서접수");

  const add = () => {
    if (!d || !title.trim()) return;
    saveEvents([...events, { id: "e_" + Date.now(), d, title: title.trim(), univ: univ.trim() || "공통", type }]);
    setTitle(""); setUniv("");
  };
  const remove = (id) => saveEvents(events.filter(e => e.id !== id));

  const sorted = [...events].sort((a, b) => a.d.localeCompare(b.d));
  const groups = sorted.reduce((acc, e) => {
    const k = e.d.slice(0, 7);
    (acc[k] = acc[k] || []).push(e);
    return acc;
  }, {});

  return (
    <div className="space-y-5 max-w-3xl">
      <div className="bg-white rounded-xl border border-slate-200 p-4 space-y-3">
        <p className="text-sm font-extrabold text-slate-700">일정 추가</p>
        <div className="grid grid-cols-2 gap-3">
          <Field label="날짜 *"><input type="date" className={inputCls} value={d} onChange={e => setD(e.target.value)} /></Field>
          <Field label="구분">
            <select className={inputCls} value={type} onChange={e => setType(e.target.value)}>
              {EVENT_TYPES.map(t => <option key={t}>{t}</option>)}
            </select>
          </Field>
        </div>
        <div className="grid grid-cols-2 gap-3">
          <Field label="일정명 *"><input className={inputCls} value={title} onChange={e => setTitle(e.target.value)} placeholder="예: 논술고사 (인문)" /></Field>
          <Field label="대학"><input className={inputCls} value={univ} onChange={e => setUniv(e.target.value)} placeholder="예: 경희대" /></Field>
        </div>
        <button onClick={add} className="w-full bg-slate-900 text-white rounded-lg py-2.5 text-sm font-bold hover:bg-slate-700">일정 추가</button>
      </div>

      <p className="text-xs text-slate-400">※ 시행계획 단계에는 세부 일정이 미확정입니다. 기본 제공 일정은 예상치이며 삭제 가능합니다. 모집요강 발표 후 대학별 일정을 입력해 쓰세요.</p>

      {Object.keys(groups).length === 0 ? (
        <div className="bg-white border border-dashed border-slate-300 rounded-xl p-8 text-center text-sm text-slate-400">등록된 일정이 없습니다.</div>
      ) : (
        Object.entries(groups).map(([month, list]) => (
          <div key={month}>
            <p className="text-sm font-extrabold text-slate-500 mb-2">{month.slice(0, 4)}년 {parseInt(month.slice(5), 10)}월</p>
            <div className="bg-white rounded-xl border border-slate-200 divide-y divide-slate-100 overflow-hidden">
              {list.map(e => {
                const dd = dday(e.d);
                return (
                  <div key={e.id} className="px-4 py-2.5 flex items-center gap-3">
                    <span className="text-sm font-bold tabular-nums text-slate-700 w-20 shrink-0">{e.d.slice(5).replace("-", "/")}</span>
                    <span className={`text-[10px] font-bold px-1.5 py-0.5 rounded ring-1 shrink-0 ${EVENT_COLORS[e.type] || EVENT_COLORS["기타"]}`}>{e.type}</span>
                    <span className="text-xs font-bold text-slate-500 shrink-0">{e.univ}</span>
                    <span className="text-sm text-slate-700 truncate">{e.title}</span>
                    {dd >= 0 && dd <= 365 && (
                      <span className={`ml-auto text-xs font-extrabold tabular-nums shrink-0 ${dd <= 7 ? "text-rose-600" : "text-slate-400"}`}>D-{dd === 0 ? "DAY" : dd}</span>
                    )}
                    <button onClick={() => remove(e.id)} className={`${dd >= 0 && dd <= 365 ? "" : "ml-auto"} text-slate-300 hover:text-rose-500 shrink-0`}><Trash2 size={13} /></button>
                  </div>
                );
              })}
            </div>
          </div>
        ))
      )}
    </div>
  );
}

