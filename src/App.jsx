function Field({ label, children }) {
  return (
    <label className="block">
      <span className="text-xs font-bold text-slate-500">{label}</span>
      <div className="mt-1">{children}</div>
    </label>
  );
}

const inputCls = "w-full rounded-lg border border-slate-300 px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-slate-400 bg-white";

function DataManager({ univs, edits, onSave, onReset, onExport, onImport }) {
  const [mode, setMode] = useState("adm"); // adm | unit | univ | log
  const [target, setTarget] = useState(univs[0]?.id || "");
  const [msg, setMsg] = useState("");

  const [aType, setAType] = useState("교과");
  const [aName, setAName] = useState("");
  const [aQ, setAQ] = useState("");
  const [aMin, setAMin] = useState("");
  const [aM, setAM] = useState("");

  const [uName, setUName] = useState("");
  const [uTrack, setUTrack] = useState("인문");
  const [uQ, setUQ] = useState("");

  const [nvName, setNvName] = useState("");
  const [nvRegion, setNvRegion] = useState("");
  const [nvChanges, setNvChanges] = useState("");

  const [logNote, setLogNote] = useState("");

  const flash = (t) => { setMsg(t); setTimeout(() => setMsg(""), 3000); };

  const addAdm = () => {
    if (!aName.trim() || !aM.trim()) { flash("전형명과 전형방법은 필수입니다."); return; }
    const next = JSON.parse(JSON.stringify(edits));
    if (!next.admAdds[target]) next.admAdds[target] = [];
    next.admAdds[target].push({ t: aType, n: aName.trim(), q: aQ.trim() || null, min: aMin.trim() || null, m: aM.trim() });
    onSave(next);
    setAName(""); setAQ(""); setAMin(""); setAM("");
    flash("전형이 추가되었습니다. 대학별 탭에서 확인하세요.");
  };

  const addUnit = () => {
    if (!uName.trim() || !uQ.trim()) { flash("모집단위명과 인원 정보는 필수입니다."); return; }
    const pairs = uQ.split(",").map(s => s.trim()).filter(Boolean).map(s => {
      const idx = s.lastIndexOf(":");
      if (idx === -1) return [s, ""];
      return [s.slice(0, idx).trim(), s.slice(idx + 1).trim()];
    });
    const next = JSON.parse(JSON.stringify(edits));
    if (!next.unitAdds[target]) next.unitAdds[target] = [];
    next.unitAdds[target].push({ n: uName.trim(), tr: uTrack, q: pairs });
    onSave(next);
    setUName(""); setUQ("");
    flash("모집단위가 추가되었습니다.");
  };

  const addUniv = () => {
    if (!nvName.trim()) { flash("대학명은 필수입니다."); return; }
    const next = JSON.parse(JSON.stringify(edits));
    next.customUnivs.push({
      id: "c_" + Date.now(),
      name: nvName.trim(),
      region: nvRegion.trim() || "직접 입력",
      changes: nvChanges.split("\n").map(s => s.trim()).filter(Boolean),
      adms: [], units: [], record: null, jeongsi: null, _custom: true,
    });
    onSave(next);
    setNvName(""); setNvRegion(""); setNvChanges("");
    flash("대학이 추가되었습니다. 이어서 전형을 추가해 주세요.");
  };

  const removeUniv = (id) => {
    const next = JSON.parse(JSON.stringify(edits));
    next.customUnivs = next.customUnivs.filter(u => u.id !== id);
    delete next.admAdds[id]; delete next.unitAdds[id]; delete next.updates[id];
    onSave(next);
  };

  const addLog = () => {
    if (!logNote.trim()) { flash("수정 내용을 입력하세요."); return; }
    const next = JSON.parse(JSON.stringify(edits));
    if (!next.updates) next.updates = {};
    if (!next.updates[target]) next.updates[target] = [];
    const today = new Date().toISOString().slice(0, 10);
    next.updates[target].push({ d: today, note: logNote.trim() });
    onSave(next);
    setLogNote("");
    flash("이력이 기록되었습니다. 해당 대학 상세 상단에 표시됩니다.");
  };

  const removeLog = (univId, idx) => {
    const next = JSON.parse(JSON.stringify(edits));
    next.updates[univId].splice(idx, 1);
    if (next.updates[univId].length === 0) delete next.updates[univId];
    onSave(next);
  };

  const handleImportFile = (e) => {
    const file = e.target.files && e.target.files[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = () => {
      const ok = onImport(reader.result);
      flash(ok ? "가져오기 완료 — 전체 데이터가 교체되었습니다." : "파일 형식 오류 — 이 앱에서 내보낸 JSON인지 확인하세요.");
    };
    reader.readAsText(file);
    e.target.value = "";
  };

  const admCount = Object.values(edits.admAdds).reduce((a, b) => a + b.length, 0);
  const unitCount = Object.values(edits.unitAdds).reduce((a, b) => a + b.length, 0);
  const logEntries = Object.entries(edits.updates || {});

  return (
    <div className="space-y-5 max-w-3xl">
      <div className="bg-cyan-50 border border-cyan-200 rounded-xl p-4 text-sm text-cyan-900 flex gap-2">
        <Info size={16} className="shrink-0 mt-0.5" />
        <div>
          입력한 내용은 이 브라우저에 저장되어 다음에 열어도 유지됩니다. 다른 컴퓨터·동료 교사와 공유하려면 아래 내보내기/가져오기를 사용하세요.
          <div className="mt-1 text-xs text-cyan-700">현재 추가분 — 대학 {edits.customUnivs.length} · 전형 {admCount} · 모집단위 {unitCount} · 이력 {logEntries.length}개 대학</div>
        </div>
      </div>

      {/* 내보내기 / 가져오기 */}
      <div className="bg-white rounded-xl border border-slate-200 p-4">
        <p className="text-sm font-extrabold text-slate-700 mb-3">백업 · 공유 (JSON)</p>
        <div className="flex flex-wrap gap-2">
          <button onClick={onExport} className="flex items-center gap-1.5 bg-slate-900 text-white rounded-lg px-4 py-2 text-sm font-bold hover:bg-slate-700">
            <Download size={14} /> 내보내기
          </button>
          <label className="flex items-center gap-1.5 bg-white border border-slate-300 text-slate-700 rounded-lg px-4 py-2 text-sm font-bold hover:border-slate-500 cursor-pointer">
            <Upload size={14} /> 가져오기
            <input type="file" accept=".json,application/json" className="hidden" onChange={handleImportFile} />
          </label>
        </div>
        <p className="mt-2 text-xs text-slate-400">추가 데이터·관심 학생·일정·이력이 모두 포함됩니다. 가져오기는 현재 데이터를 교체합니다.</p>
      </div>

      <div className="flex flex-wrap gap-2">
        {[["adm","전형 추가"],["unit","모집단위 추가"],["univ","대학 추가"],["log","변경 이력 기록"]].map(([k, label]) => (
          <button key={k} onClick={() => setMode(k)}
            className={`px-3 py-1.5 rounded-full text-sm font-semibold border ${mode===k ? "bg-slate-900 text-white border-slate-900" : "bg-white text-slate-600 border-slate-200 hover:border-slate-400"}`}>
            {k === "log" ? <Pencil size={13} className="inline -mt-0.5 mr-1" /> : <Plus size={13} className="inline -mt-0.5 mr-1" />}{label}
          </button>
        ))}
      </div>

      {msg && <div className="text-sm font-semibold text-emerald-700 bg-emerald-50 border border-emerald-200 rounded-lg px-3 py-2">{msg}</div>}

      {(mode === "adm" || mode === "unit" || mode === "log") && (
        <Field label="대상 대학">
          <select className={inputCls} value={target} onChange={e => setTarget(e.target.value)}>
            {univs.map(u => <option key={u.id} value={u.id}>{u.name}</option>)}
          </select>
        </Field>
      )}

      {mode === "adm" && (
        <div className="bg-white rounded-xl border border-slate-200 p-4 space-y-3">
          <div className="grid grid-cols-2 gap-3">
            <Field label="전형 유형">
              <select className={inputCls} value={aType} onChange={e => setAType(e.target.value)}>
                {["교과","종합","논술","정시","기타"].map(t => <option key={t}>{t}</option>)}
              </select>
            </Field>
            <Field label="모집인원 (예: 120)">
              <input className={inputCls} value={aQ} onChange={e => setAQ(e.target.value)} placeholder="숫자 또는 텍스트" />
            </Field>
          </div>
          <Field label="전형명 *">
            <input className={inputCls} value={aName} onChange={e => setAName(e.target.value)} placeholder="예: 지역균형" />
          </Field>
          <Field label="전형 방법 *">
            <input className={inputCls} value={aM} onChange={e => setAM(e.target.value)} placeholder="예: 교과90 + 출결10" />
          </Field>
          <Field label="수능최저 (없으면 비워두기)">
            <input className={inputCls} value={aMin} onChange={e => setAMin(e.target.value)} placeholder="예: 국수영탐(1) 3합7, 한4" />
          </Field>
          <button onClick={addAdm} className="w-full bg-slate-900 text-white rounded-lg py-2.5 text-sm font-bold hover:bg-slate-700">전형 추가</button>
        </div>
      )}

      {mode === "unit" && (
        <div className="bg-white rounded-xl border border-slate-200 p-4 space-y-3">
          <div className="grid grid-cols-2 gap-3">
            <Field label="모집단위명 *">
              <input className={inputCls} value={uName} onChange={e => setUName(e.target.value)} placeholder="예: 화학과" />
            </Field>
            <Field label="계열">
              <select className={inputCls} value={uTrack} onChange={e => setUTrack(e.target.value)}>
                {["인문","자연","공통","예체능","기타"].map(t => <option key={t}>{t}</option>)}
              </select>
            </Field>
          </div>
          <Field label="전형별 인원 * — 형식: 전형명:인원, 전형명:인원">
            <input className={inputCls} value={uQ} onChange={e => setUQ(e.target.value)} placeholder="예: 지역균형:8, 면접형:10, 논술:6" />
          </Field>
          <button onClick={addUnit} className="w-full bg-slate-900 text-white rounded-lg py-2.5 text-sm font-bold hover:bg-slate-700">모집단위 추가</button>
        </div>
      )}

      {mode === "univ" && (
        <div className="bg-white rounded-xl border border-slate-200 p-4 space-y-3">
          <div className="grid grid-cols-2 gap-3">
            <Field label="대학명 *">
              <input className={inputCls} value={nvName} onChange={e => setNvName(e.target.value)} placeholder="예: 서울시립대" />
            </Field>
            <Field label="지역">
              <input className={inputCls} value={nvRegion} onChange={e => setNvRegion(e.target.value)} placeholder="예: 서울" />
            </Field>
          </div>
          <Field label="주요 변경사항 (줄바꿈으로 구분, 선택)">
            <textarea className={inputCls + " h-24"} value={nvChanges} onChange={e => setNvChanges(e.target.value)} placeholder="한 줄에 하나씩 입력" />
          </Field>
          <button onClick={addUniv} className="w-full bg-slate-900 text-white rounded-lg py-2.5 text-sm font-bold hover:bg-slate-700">대학 추가</button>

          {edits.customUnivs.length > 0 && (
            <div className="pt-2 border-t border-slate-100">
              <p className="text-xs font-bold text-slate-500 mb-2">추가한 대학</p>
              {edits.customUnivs.map(u => (
                <div key={u.id} className="flex items-center justify-between py-1.5 text-sm">
                  <span className="font-semibold text-slate-700">{u.name} <span className="text-slate-400 font-normal">({u.region})</span></span>
                  <button onClick={() => removeUniv(u.id)} className="text-slate-400 hover:text-rose-500"><Trash2 size={14} /></button>
                </div>
              ))}
            </div>
          )}
        </div>
      )}

      {mode === "log" && (
        <div className="bg-white rounded-xl border border-slate-200 p-4 space-y-3">
          <p className="text-xs text-slate-500">모집요강 확정 등으로 데이터가 바뀌었을 때 기록하세요. 해당 대학 상세 상단과 대학 목록에 <Pencil size={11} className="inline text-cyan-500 -mt-0.5" /> 표시가 붙습니다.</p>
          <Field label="수정 내용 *">
            <input className={inputCls} value={logNote} onChange={e => setLogNote(e.target.value)}
              onKeyDown={e => { if (e.key === "Enter") addLog(); }}
              placeholder="예: 요강 확정 — 논술 인원 469 → 455로 변경" />
          </Field>
          <button onClick={addLog} className="w-full bg-slate-900 text-white rounded-lg py-2.5 text-sm font-bold hover:bg-slate-700">이력 기록</button>

          {logEntries.length > 0 && (
            <div className="pt-2 border-t border-slate-100 space-y-2">
              <p className="text-xs font-bold text-slate-500">기록된 이력</p>
              {logEntries.map(([uid, logs]) => {
                const un = univs.find(u => u.id === uid);
                return logs.map((lg, i) => (
                  <div key={uid + i} className="flex items-center gap-2 text-sm py-1">
                    <span className="font-bold text-slate-700 w-20 shrink-0">{un ? un.name : uid}</span>
                    <span className="text-xs tabular-nums text-slate-400 shrink-0">{lg.d}</span>
                    <span className="text-slate-600 truncate">{lg.note}</span>
                    <button onClick={() => removeLog(uid, i)} className="ml-auto text-slate-300 hover:text-rose-500 shrink-0"><Trash2 size={13} /></button>
                  </div>
                ));
              })}
            </div>
          )}
        </div>
      )}

      <button onClick={onReset} className="flex items-center gap-1.5 text-xs text-slate-400 hover:text-rose-500">
        <RotateCcw size={13} /> 추가한 전형·모집단위·대학·이력 초기화 (관심 학생·일정은 유지)
      </button>
    </div>
  );
}

