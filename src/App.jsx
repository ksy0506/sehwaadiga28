const M_num = (v) => {
  if (v === null || v === undefined || v === "") return NaN;
  const n = typeof v === "number" ? v : parseFloat(String(v).replace(/,/g, "").trim());
  return Number.isFinite(n) ? n : NaN;
};
const M_sid = (v) => {
  if (v === null || v === undefined || v === "") return "";
  const n = M_num(v);
  return Number.isFinite(n) ? String(Math.round(n)) : String(v).trim();
};
const M_mean = (arr) => {
  const a = arr.filter((x) => Number.isFinite(x));
  return a.length ? a.reduce((s, x) => s + x, 0) / a.length : NaN;
};
const M_rows = (XLSX, ws) => {
  if (!ws || !ws["!ref"]) return [];
  const r = XLSX.utils.decode_range(ws["!ref"]);
  r.s.r = 0; r.s.c = 0;
  return XLSX.utils.sheet_to_json(ws, { header: 1, range: r, defval: null, raw: true, blankrows: true });
};

/* 파일 종류 판별 */
function M_detect(wb) {
  const s = wb.SheetNames;
  if (s.includes("수시") && s.includes("정시") && s.includes("내신성적") && s.includes("모의고사 성적")) return "grad";
  if (s.includes("명렬") && s.includes("1학기종합(2학년)")) return "cur";
  return null;
}

/* 졸업생 파일 */
function M_parseGrad(XLSX, wb) {
  const S = (n) => M_rows(XLSX, wb.Sheets[n]);
  const g = {};
  const get = (id) => (g[id] = g[id] || { id, tr: "", nae: NaN, mocks: [], engs: [] });

  // 내신: 1-1(6), 1-2(7), 2-1(9) 평균 (9등급제)
  S("내신성적").slice(3).forEach((r) => {
    const id = M_sid(r[1]);
    if (!/^\d{5}$/.test(id)) return;
    const vals = [M_num(r[6]), M_num(r[7]), M_num(r[9])].filter(Number.isFinite);
    if (vals.length >= 2) get(id).nae = M_mean(vals);
  });
  // 계열: 학년이력 col0=3학년 학번, col5=계열
  S("학년이력").slice(1).forEach((r) => {
    const id = M_sid(r[0]);
    if (!/^\d{5}$/.test(id)) return;
    const t = String(r[5] || "").trim();
    if (t === "인문" || t === "자연") get(id).tr = t;
  });
  // 모의: 코드 = 학년(1)+월(2)+3학년학번(5), 2학년 3월·9월만
  S("모의고사 성적").slice(2).forEach((r) => {
    const code = M_sid(r[0]);
    if (code.length < 8) return;
    const grade = code[0], month = code.slice(1, 3), id = code.slice(-5);
    if (grade !== "2" || (month !== "03" && month !== "09")) return;
    const kuk = M_num(r[7]), su = M_num(r[16]);
    const tam = M_mean([M_num(r[27]), M_num(r[33])]);
    if ([kuk, su, tam].every(Number.isFinite)) get(id).mocks.push((kuk + su + tam) / 3);
    const e = M_num(r[21]);
    if (Number.isFinite(e)) get(id).engs.push(e);
  });

  const results = [];
  S("수시").slice(1).forEach((r) => {
    const id = M_sid(r[1]), univ = String(r[4] || "").trim();
    if (!/^\d{5}$/.test(id) || !univ || univ === "None") return;
    let type = String(r[15] || "").trim();
    if (type === "실기위주") type = "실기";
    if (!["논술", "종합", "교과", "실기"].includes(type)) type = "기타";
    results.push({ g: id, univ, unit: String(r[8] || "").trim(), adm: String(r[6] || "").trim(),
      type, pass: String(r[10] || "").trim() === "합" });
  });
  S("정시").slice(1).forEach((r) => {
    const id = M_sid(r[1]), univ = String(r[4] || "").trim();
    if (!/^\d{5}$/.test(id) || !univ || univ === "None") return;
    results.push({ g: id, univ, unit: String(r[8] || "").trim(), adm: String(r[5] || "").trim(),
      type: "정시", pass: String(r[10] || "").trim() === "합" });
  });

  // 교내 순위는 내신이 있는 졸업생 전원 기준(재학생과 같은 방식), 매칭 대상은 지원 기록이 있는 선배만
  const all = Object.values(g).map((x) => ({ id: x.id, tr: x.tr, nae: x.nae, mock: M_mean(x.mocks), eng: M_mean(x.engs) }));
  M_addTop(all);
  const withRes = new Set(results.map((x) => x.g));
  const grads = all.filter((x) => withRes.has(x.id));
  const scale = all.filter((x) => Number.isFinite(x.top) && Number.isFinite(x.nae))
    .sort((a, b) => a.top - b.top).map((x) => [Math.round(x.top * 10) / 10, Math.round(x.nae * 100) / 100]);
  return { grads, results, scale };
}

