/* 전형 상세 조회 헬퍼 — allUnivs에서 admName으로 매칭 */
function lookupAdm(allUnivs, univId, admName) {
  const u = allUnivs.find(x => x.id === univId);
  if (!u) return null;
  /* admName이 "지역균형", "일반전형" 같은 전형명일 수도 있고 "정시 일반" 같은 약칭일 수도 있음 → 부분 매칭 */
  return u.adms.find(a => a.n === admName || admName.includes(a.n) || a.n.includes(admName)) || null;
}

