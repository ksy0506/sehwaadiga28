/* 재학생 파일 (현재 2학년) */
function M_parseCur(XLSX, wb) {
  const S = (n) => M_rows(XLSX, wb.Sheets[n]);
  const map1to2 = {};
  S("명렬").slice(1).forEach((r) => {
    const a = M_sid(r[0]), b = M_sid(r[4]);
    if (a && b) map1to2[a] = b;
  });
  const st = {};
  // 2학년 1학기 종합: 명단 + 내신 + 계열 추정
  S("1학기종합(2학년)").slice(2).forEach((r) => {
    const id = M_sid(r[0]);
    if (!/^\d{5}$/.test(id)) return;
    const soc = [10, 11, 12, 13].filter((j) => r[j] !== null && r[j] !== "").length;
    const sci = [14, 15, 16, 17].filter((j) => r[j] !== null && r[j] !== "").length;
    const tr = sci >= 3 ? "자연" : soc >= 3 ? "인문" : "";
    st[id] = { id, ban: M_num(r[1]), no: M_num(r[2]), name: String(r[3] || "").trim(), tr,
      sem: [], mocks: [], engs: [] };
    const gr = M_num(r[23]), u = M_num(r[22]);
    if (Number.isFinite(gr) && Number.isFinite(u) && u > 0) st[id].sem.push([gr, u]);
  });
  // 1학년 1·2학기 (학번은 1학년 학번 → 명렬로 2학년 학번)
  ["1학기종합", "2학기종합"].forEach((name) => {
    S(name).slice(1).forEach((r) => {
      const id = map1to2[M_sid(r[0])];
      if (!id || !st[id]) return;
      const gr = M_num(r[17]), u = M_num(r[16]);
      if (Number.isFinite(gr) && Number.isFinite(u) && u > 0) st[id].sem.push([gr, u]);
    });
  });
  // 2학년 3월·9월 모의: 국백6 수백10 사회백18 과학백22 영등급13
  ["3월(2학년)", "9월(2학년)"].forEach((name) => {
    S(name).slice(3).forEach((r) => {
      const id = M_sid(r[0]);
      if (!st[id]) return;
      const kuk = M_num(r[6]), su = M_num(r[10]);
      const tam = M_mean([M_num(r[18]), M_num(r[22])]);
      if ([kuk, su, tam].every(Number.isFinite)) st[id].mocks.push((kuk + su + tam) / 3);
      const e = M_num(r[13]);
      if (Number.isFinite(e)) st[id].engs.push(e);
    });
  });
  // 수능최저 판정용: 2학년 3·6·9·10월 등급 [국, 수, 영, 한국사, 사회, 과학]
  M_EXAMS.forEach((m) => {
    S(`${m}(2학년)`).slice(3).forEach((r) => {
      const id = M_sid(r[0]);
      if (!st[id]) return;
      const g = [7, 11, 13, 15, 19, 23].map((j) => { const v = M_num(r[j]); return Number.isFinite(v) && v >= 1 && v <= 9 ? v : null; });
      if (g.some((v) => v !== null)) (st[id].ex = st[id].ex || {})[m] = g;
    });
  });
  const students = Object.values(st).map((x) => {
    const su = x.sem.reduce((s, [, u]) => s + u, 0);
    const nae = su ? x.sem.reduce((s, [gr, u]) => s + gr * u, 0) / su : NaN;
    return { id: x.id, ban: x.ban, no: x.no, name: x.name, tr: x.tr, nae, semCount: x.sem.length,
      mock: M_mean(x.mocks), mockCount: x.mocks.length, eng: M_mean(x.engs), ex: x.ex || {} };
  });
  M_addTop(students);
  students.sort((a, b) => (a.ban - b.ban) || (a.no - b.no));
  return { students };
}

/* 교내 석차 백분율(상위 %): 평균등급 낮을수록 상위, 동점은 평균 순위 */
function M_addTop(list) {
  const v = list.filter((x) => Number.isFinite(x.nae)).sort((a, b) => a.nae - b.nae);
  const N = v.length;
  let i = 0;
  while (i < N) {
    let j = i;
    while (j + 1 < N && v[j + 1].nae === v[i].nae) j++;
    const top = (((i + j) / 2 + 1) - 0.5) / N * 100;
    for (let k = i; k <= j; k++) v[k].top = top;
    i = j + 1;
  }
  list.forEach((x) => { if (!Number.isFinite(x.top)) x.top = NaN; });
}

const M_sd = (arr) => {
  const a = arr.filter(Number.isFinite);
  if (a.length < 2) return 1;
  const m = a.reduce((s, x) => s + x, 0) / a.length;
  return Math.sqrt(a.reduce((s, x) => s + (x - m) ** 2, 0) / (a.length - 1)) || 1;
};

/* 비슷한 선배 찾기. w: 0 = 모의만(정시형) … 1 = 내신만(수시형) */
function M_findSimilar(student, grads, { w = 0.5, k = 15, tr = "" } = {}) {
  const hasN = Number.isFinite(student.top), hasM = Number.isFinite(student.mock);
  let wn = w, mode = "both";
  if (hasN && !hasM) { wn = 1; mode = "naeOnly"; }
  else if (!hasN && hasM) { wn = 0; mode = "mockOnly"; }
  else if (!hasN && !hasM) return { mode: "none", list: [], close: 0 };
  const sdn = M_sd(grads.map((x) => x.top)), sdm = M_sd(grads.map((x) => x.mock));
  const pool = grads.filter((x) => (!tr || x.tr === tr)
    && (wn === 0 || Number.isFinite(x.top)) && (wn === 1 || Number.isFinite(x.mock)));
  const list = pool.map((x) => {
    const dn = wn > 0 ? (x.top - student.top) / sdn : 0;
    const dm = wn < 1 ? (x.mock - student.mock) / sdm : 0;
    return { ...x, d: Math.sqrt(wn * dn * dn + (1 - wn) * dm * dm) };
  }).sort((a, b) => a.d - b.d);
  const close = list.filter((x) => x.d <= M_CLOSE).length;
  return { mode, list: list.slice(0, k), close, pool: pool.length };
}
const M_CLOSE = 0.35; // 표준편차 단위: 이 거리 안의 선배가 5명 미만이면 '참고 자료 부족'

/* 선배 결과 집계 (대학별) */
function M_summarize(neighbors, results) {
  const ids = new Set(neighbors.map((x) => x.id));
  const rows = results.filter((r) => ids.has(r.g));
  const by = {};
  rows.forEach((r) => {
    const u = (by[r.univ] = by[r.univ] || { univ: r.univ, app: new Set(), pass: new Set(), types: {}, units: [] });
    u.app.add(r.g);
    if (r.pass) {
      u.pass.add(r.g);
      u.types[r.type] = (u.types[r.type] || 0) + 1;
      u.units.push({ unit: r.unit, type: r.type, g: r.g });
    }
  });
  const univs = Object.values(by).map((u) => ({ univ: u.univ, app: u.app.size, pass: u.pass.size, types: u.types, units: u.units }))
    .sort((a, b) => (b.pass - a.pass) || (b.app - a.app) || a.univ.localeCompare(b.univ, "ko"));
  const passBy = {};
  rows.filter((r) => r.pass).forEach((r) => { (passBy[r.g] = passBy[r.g] || []).push(r); });
  const anySusi = neighbors.filter((x) => (passBy[x.id] || []).some((r) => r.type !== "정시")).length;
  const anyJeong = neighbors.filter((x) => (passBy[x.id] || []).some((r) => r.type === "정시")).length;
  return { univs, passBy, anySusi, anyJeong };
}

/* 교내 상위 %에 해당하는 졸업생 9등급제 평균 (scale: [상위%, 평균등급] 오름차순, 직선 보간) */
function M_equiv9(top, scale) {
  if (!Number.isFinite(top) || !scale || !scale.length) return NaN;
  if (top <= scale[0][0]) return scale[0][1];
  const last = scale[scale.length - 1];
  if (top >= last[0]) return last[1];
  for (let i = 1; i < scale.length; i++) {
    if (top <= scale[i][0]) {
      const [t0, n0] = scale[i - 1], [t1, n1] = scale[i];
      return t1 === t0 ? n1 : n0 + (top - t0) / (t1 - t0) * (n1 - n0);
    }
  }
  return NaN;
}

